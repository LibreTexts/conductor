import { AsyncLocalStorage } from "node:async_hooks";
import { ExpertError } from "@libretexts/cxone-expert-node";
import { childLogger } from "../../logger.js";

const log = childLogger("cxone-gate");

const bulkContext = new AsyncLocalStorage<{ maxWaitMs: number }>();

/**
 * Runs `fn` with every CXOne request it makes (including async work it starts)
 * queued behind interactive requests. Wrap job runners and fan-outs, never a
 * single user-facing call: unmarked work is interactive by default.
 *
 * Jobs wait in the queue as long as needed. Pass `maxWaitMs` for low-priority
 * work inside a request, which must give up before the client does.
 */
export function runAsBulk<T>(fn: () => Promise<T>, maxWaitMs = Infinity): Promise<T> {
  // A nested limit never shortens an outer job's wait.
  const outer = bulkContext.getStore()?.maxWaitMs ?? 0;
  return bulkContext.run({ maxWaitMs: Math.max(maxWaitMs, outer) }, fn);
}

/**
 * Thrown instead of sending a request while the libraries' edge is blocking
 * Conductor. Carries how long until the gate will try again.
 */
export class CXOneUnavailableError extends Error {
  constructor(public readonly retryAfterMs: number, reason = "CXOne is refusing Conductor's requests") {
    super(`${reason}; retrying in ${Math.ceil(retryAfterMs / 1000)}s`);
    this.name = "CXOneUnavailableError";
  }
}

/**
 * True when the libraries' CDN/WAF refused the request, as opposed to MindTouch
 * itself. A MindTouch permission 403 is XML/JSON from the origin; tripping on
 * it would let one private page take every library offline.
 */
export function isUpstreamBlock(status: number | undefined, body: unknown): boolean {
  if (status === 429) return true;
  return (
    status === 403 &&
    typeof body === "string" &&
    body.toLowerCase().includes("generated by cloudfront")
  );
}

export type CXOneGateOptions = {
  maxInFlight: number;
  minIntervalMs: number;
  baseCooldownMs: number;
  maxCooldownMs: number;
  /** Longest an interactive call waits for a slot before failing fast. */
  maxQueueWaitMs: number;
};

// shortcut: limits are per container, so N tasks send N× the rate. Move to a
// shared limiter (Redis) if task count grows or blocks recur.
const DEFAULTS: CXOneGateOptions = {
  maxInFlight: 6,
  minIntervalMs: 100,
  baseCooldownMs: 60_000,
  maxCooldownMs: 15 * 60_000,
  // Well under the load balancer timeout, so callers get a 503 instead of an abort.
  maxQueueWaitMs: 15_000,
};

/**
 * One budget for every CXOne request this process sends. All library
 * subdomains sit behind the same vendor WAF, which counts per source IP, so the
 * budget is global rather than per library.
 *
 * Paces requests (concurrency cap plus a minimum gap between starts) and runs a
 * circuit breaker: once the edge blocks us, every caller fails fast with
 * {@link CXOneUnavailableError} until a single probe gets through. Sending
 * nothing is what lets a rate-based block expire.
 */
export class CXOneGate {
  private inFlight = 0;
  private waiters: (() => void)[] = [];
  private bulkWaiters: (() => void)[] = [];
  private nextStartAt = 0;
  /** 0 while closed. */
  private openUntil = 0;
  private probing = false;
  private cooldownMs: number;

  constructor(private readonly opts: CXOneGateOptions = DEFAULTS) {
    this.cooldownMs = opts.baseCooldownMs;
  }

  /** Runs an SDK call. Blocks surface as thrown {@link ExpertError}s. */
  run<T>(fn: () => Promise<T>): Promise<T> {
    return this._run(fn, async (outcome) =>
      "error" in outcome &&
      ExpertError.isExpertError(outcome.error) &&
      isUpstreamBlock(outcome.error.status, outcome.error.responseData),
    );
  }

  /** `fetch` through the gate. Blocks surface as a resolved 403/429 Response. */
  fetch(input: string | URL, init?: RequestInit): Promise<Response> {
    return this._run(
      () => fetch(input, init),
      async (outcome) => {
        if (!("value" in outcome)) return false;
        const { status } = outcome.value;
        if (status !== 403 && status !== 429) return false;
        return isUpstreamBlock(status, await outcome.value.clone().text());
      },
    );
  }

  private async _run<T>(
    fn: () => Promise<T>,
    isBlock: (outcome: { value: T } | { error: unknown }) => Promise<boolean>,
  ): Promise<T> {
    this.rejectIfOpen();
    await this.acquire();
    let isProbe = false;
    try {
      // The breaker can open while this call waits in the queue. Fail before pace() books a slot.
      this.rejectIfOpen();
      await this.pace();
      isProbe = this.admit();

      let outcome: { value: T } | { error: unknown };
      try {
        outcome = { value: await fn() };
      } catch (error) {
        outcome = { error };
      }

      const blocked = await isBlock(outcome).catch(() => false);
      this.record(blocked, isProbe);
      isProbe = false;

      if ("error" in outcome) throw outcome.error;
      return outcome.value;
    } finally {
      if (isProbe) this.probing = false;
      this.release();
    }
  }

  /** ms until the breaker would admit a request; 0 when it would admit one now. */
  get retryAfterMs(): number {
    if (this.openUntil === 0) return 0;
    return Math.max(this.openUntil - Date.now(), this.probing ? 1000 : 0);
  }

  /**
   * Resolves once the breaker would admit a request. Throws
   * {@link CXOneUnavailableError} instead if that is later than `deadline`.
   */
  async waitUntilClosed(deadline: number): Promise<void> {
    for (let wait = this.retryAfterMs; wait > 0; wait = this.retryAfterMs) {
      if (Date.now() + wait > deadline) throw new CXOneUnavailableError(wait);
      await new Promise((resolve) => setTimeout(resolve, wait));
    }
  }

  /** Fail fast while open, before queueing. The probe slot is claimed later, in admit(). */
  private rejectIfOpen(): void {
    if (this.openUntil === 0) return;
    const wait = this.openUntil - Date.now();
    if (wait > 0 || this.probing) {
      throw new CXOneUnavailableError(Math.max(wait, 1000));
    }
  }

  /** Re-checks after the wait in the queue. Returns true when this call is the half-open probe. */
  private admit(): boolean {
    if (this.openUntil === 0) return false;
    this.rejectIfOpen();
    this.probing = true;
    return true;
  }

  private record(blocked: boolean, isProbe: boolean): void {
    if (blocked) {
      if (this.openUntil === 0) {
        this.cooldownMs = this.opts.baseCooldownMs;
        log.warn({ cooldownMs: this.cooldownMs }, "CXOne edge is blocking requests; breaker open");
      } else if (isProbe) {
        this.cooldownMs = Math.min(this.cooldownMs * 2, this.opts.maxCooldownMs);
        log.warn({ cooldownMs: this.cooldownMs }, "CXOne probe still blocked; breaker stays open");
      }
      this.openUntil = Date.now() + this.cooldownMs;
    } else if (isProbe) {
      this.openUntil = 0;
      this.cooldownMs = this.opts.baseCooldownMs;
      log.warn("CXOne probe got through; breaker closed");
    }
    if (isProbe) this.probing = false;
  }

  private async acquire(): Promise<void> {
    if (this.inFlight < this.opts.maxInFlight) {
      this.inFlight++;
      return;
    }
    // release() hands its slot straight to the next waiter, so inFlight stays put.
    const bulk = bulkContext.getStore();
    const queue = bulk ? this.bulkWaiters : this.waiters;
    const maxWaitMs = bulk ? bulk.maxWaitMs : this.opts.maxQueueWaitMs;
    await new Promise<void>((resolve, reject) => {
      let timer: ReturnType<typeof setTimeout> | undefined;
      const waiter = () => {
        clearTimeout(timer);
        resolve();
      };
      if (Number.isFinite(maxWaitMs)) {
        timer = setTimeout(() => {
          // Leave the queue before rejecting so release() never hands this caller a slot.
          queue.splice(queue.indexOf(waiter), 1);
          reject(new CXOneUnavailableError(5_000, "CXOne request queue is backed up"));
        }, maxWaitMs);
      }
      queue.push(waiter);
    });
  }

  // shortcut: interactive always goes first, so steady interactive load starves bulk; add an aging cap if bulk jobs stall.
  private release(): void {
    const next = this.waiters.shift() ?? this.bulkWaiters.shift();
    if (next) next();
    else this.inFlight--;
  }

  private async pace(): Promise<void> {
    const now = Date.now();
    const startAt = Math.max(now, this.nextStartAt);
    this.nextStartAt = startAt + this.opts.minIntervalMs;
    if (startAt > now) {
      await new Promise((resolve) => setTimeout(resolve, startAt - now));
    }
  }
}

const cxoneGate = new CXOneGate();
export default cxoneGate;
