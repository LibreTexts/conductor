import { useEffect, useMemo, useRef, useState } from "react";
import { Controller, useForm } from "react-hook-form";
import {
  Modal,
  Button,
  Checkbox,
  Combobox,
  IconButton,
  Input,
  FormSection,
  Stack,
  Alert,
  Text,
} from "@libretexts/davis-react";
import {
  IconArrowDown,
  IconArrowUp,
  IconCheck,
  IconCopy,
  IconDeviceFloppy,
  IconPlus,
  IconTrash,
} from "@tabler/icons-react";
import { Author } from "../../../types";
import useGlobalError from "../../error/ErrorHooks";
import api from "../../../api";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import FileUploader from "../../FileUploader";
import CampusCombobox from "./CampusCombobox";
import SimilarAuthorsModal, { SimilarPrompt, candidateChoice } from "./SimilarAuthorsModal";
import CopyButton from "../../util/CopyButton";
import { useNotifications } from "../../../context/NotificationContext";

const ALLOWED_IMAGE_TYPES = ["image/jpeg", "image/png", "image/webp"];
const MAX_IMAGE_SIZE = 5 * 1024 * 1024; // 5 MB
const MAX_PEOPLE = 20;

/**
 * The fields shared by everyone credited under this entry. pictureCircle is a boolean in the
 * form and converted to "yes"/"no" when sending to the API.
 */
type SharedFormValues = Omit<
  Author,
  | "pictureCircle"
  | "name"
  | "nameURL"
  | "groupMembers"
  | "autoName"
  | "memberOfKeys"
  | "nameKey"
  | "orgID"
> & { pictureCircle: boolean };

/** One person credited by the entry: just a name and a URL. */
type PersonRow = {
  rowId: number;
  /** Set for a person who already exists. Their details are shown but edited on their own entry. */
  nameKey?: string;
  name: string;
  nameURL: string;
};

interface ManageAuthorModalProps {
  show: boolean;
  onClose: () => void;
  authorID?: string;
}

const DEFAULT_VALUES: SharedFormValues = {
  note: "",
  noteURL: "",
  campusName: "",
  campusURL: "",
  pictureCircle: false,
  pictureURL: "",
  programName: "",
  programURL: "",
  attributionPrefix: "",
};

/**
 * Adds or edits an author entry: the record a page is tagged with. An entry credits one
 * person (a single author) or several (a group); either way every person only has a name and
 * a URL, and the campus/program shown is shared by the entry.
 */
const ManageAuthorModal = ({ show, onClose, authorID }: ManageAuthorModalProps) => {
  const queryClient = useQueryClient();
  const { addNotification } = useNotifications();
  const { handleGlobalError } = useGlobalError();
  const {
    register,
    handleSubmit,
    getValues,
    control,
    reset,
    setValue,
    watch,
    formState: { errors },
  } = useForm<SharedFormValues>({ defaultValues: DEFAULT_VALUES });

  const mode = authorID ? "edit" : "create";
  const nextRowID = useRef(1);
  const [loading, setLoading] = useState(false);
  const [uploadingImage, setUploadingImage] = useState(false);
  const [showConfirmDelete, setShowConfirmDelete] = useState(false);

  const [people, setPeople] = useState<PersonRow[]>([]);
  const [isGroup, setIsGroup] = useState(false);
  const [peopleError, setPeopleError] = useState("");
  // Read-only facts about the record being edited. Keys are generated by the server, never typed.
  const [entryKey, setEntryKey] = useState("");
  const [memberOfKeys, setMemberOfKeys] = useState<string[]>([]);
  const [originalName, setOriginalName] = useState("");
  // "Is this the same person?" prompts shown before saving, and the rows already answered.
  const [similarPrompts, setSimilarPrompts] = useState<SimilarPrompt[]>([]);
  const [confirmedDistinct, setConfirmedDistinct] = useState<number[]>([]);
  const [authorSearch, setAuthorSearch] = useState("");
  const [debouncedSearch, setDebouncedSearch] = useState("");

  const pictureURL = watch("pictureURL");
  const pictureCircle = watch("pictureCircle");
  const campusName = watch("campusName");
  const campusURL = watch("campusURL");

  // An existing single author keeps being edited as one person. Making it a group would
  // change who every page tagged with its key credits, so crediting several people is done
  // by creating a new entry instead.
  const canEditPeopleList = mode === "create" || isGroup;

  const newPerson = (init?: Partial<PersonRow>): PersonRow => ({
    rowId: nextRowID.current++,
    name: "",
    nameURL: "",
    ...init,
  });

  useEffect(() => {
    const t = setTimeout(() => setDebouncedSearch(authorSearch.trim()), 250);
    return () => clearTimeout(t);
  }, [authorSearch]);

  useEffect(() => {
    if (show) {
      setShowConfirmDelete(false);
      setPeopleError("");
      setAuthorSearch("");
      setSimilarPrompts([]);
      setConfirmedDistinct([]);
      setEntryKey("");
      setMemberOfKeys([]);
      setOriginalName("");
      if (authorID) {
        loadAuthor();
      } else {
        reset(DEFAULT_VALUES);
        setIsGroup(false);
        setPeople([newPerson()]);
      }
    }
  }, [show, authorID]);

  const { data: authorOptions = [], isFetching: searching } = useQuery({
    queryKey: ["author-picker-options", debouncedSearch],
    queryFn: async () => {
      const res = await api.getAuthors({
        query: debouncedSearch || undefined,
        limit: 20,
        page: 1,
        sort: "name",
      });
      if (res.data.err) throw new Error(res.data.errMsg);
      return res.data.items;
    },
    enabled: show && canEditPeopleList,
    staleTime: 1000 * 30,
    refetchOnWindowFocus: false,
  });

  // Groups can't contain groups, and a person can only be listed once.
  const selectableAuthors = useMemo(() => {
    const taken = new Set(people.map((p) => p.nameKey).filter(Boolean));
    return authorOptions.filter((a) => !a.groupMembers?.length && !taken.has(a.nameKey));
  }, [authorOptions, people]);

  async function loadAuthor() {
    try {
      if (!authorID) return;
      setLoading(true);
      const res = await api.getAuthor(authorID);
      if (res.data.err) throw new Error(res.data.errMsg);
      const author = res.data.author;
      if (!author) throw new Error("Invalid response from server.");

      reset({
        ...DEFAULT_VALUES,
        note: author.note ?? "",
        noteURL: author.noteURL ?? "",
        campusName: author.campusName ?? "",
        campusURL: author.campusURL ?? "",
        pictureURL: author.pictureURL ?? "",
        programName: author.programName ?? "",
        programURL: author.programURL ?? "",
        attributionPrefix: author.attributionPrefix ?? "",
        pictureCircle: author.pictureCircle === "yes",
      });
      setEntryKey(author.nameKey ?? "");
      setMemberOfKeys(author.memberOfKeys ?? []);
      setOriginalName(author.name);

      const members = author.groupMembers ?? [];
      if (members.length === 0) {
        setIsGroup(false);
        setPeople([newPerson({ name: author.name, nameURL: author.nameURL ?? "" })]);
        return;
      }

      const byKey = await api.getAuthorsByKeys(members.map((m) => m.nameKey));
      if (byKey.data.err) throw new Error(byKey.data.errMsg);
      const known = new Map(byKey.data.authors.map((a) => [a.nameKey, a]));
      setIsGroup(true);
      setPeople(
        members.map((m) =>
          newPerson({
            nameKey: m.nameKey,
            name: known.get(m.nameKey)?.name ?? m.nameKey,
            nameURL: known.get(m.nameKey)?.nameURL ?? "",
          })
        )
      );
    } catch (err) {
      handleGlobalError(err);
    } finally {
      setLoading(false);
    }
  }

  function updatePerson(rowId: number, patch: Partial<PersonRow>) {
    setPeople((prev) => prev.map((p) => (p.rowId === rowId ? { ...p, ...patch } : p)));
  }

  function movePerson(index: number, delta: -1 | 1) {
    setPeople((prev) => {
      const target = index + delta;
      if (target < 0 || target >= prev.length) return prev;
      const next = [...prev];
      [next[index], next[target]] = [next[target], next[index]];
      return next;
    });
  }

  function addExisting(author: Author | null) {
    if (!author || people.length >= MAX_PEOPLE) return;
    setPeople((prev) => [
      // Drop an untouched blank row so picking someone doesn't leave an empty one behind.
      ...prev.filter((p) => p.nameKey || p.name.trim() || p.nameURL.trim()),
      newPerson({ nameKey: author.nameKey, name: author.name, nameURL: author.nameURL ?? "" }),
    ]);
    setAuthorSearch("");
  }

  function validatePeople(): string {
    if (people.length === 0) return "Add at least one author.";
    if (people.some((p) => !p.nameKey && !p.name.trim())) return "Every author needs a name.";
    return "";
  }

  /**
   * Looks for existing authors whose names resemble the ones about to be saved. Returns
   * the prompts to show, or none when it is fine to save.
   */
  async function findSimilarPrompts(rows: PersonRow[], distinct: number[]): Promise<SimilarPrompt[]> {
    const toCheck = rows.filter(
      (p) =>
        !p.nameKey &&
        !distinct.includes(p.rowId) &&
        // An existing author is only re-checked when its name was actually changed.
        (mode === "create" || isGroup || p.name.trim() !== originalName.trim())
    );
    if (toCheck.length === 0) return [];

    const res = await api.findSimilarAuthors(
      toCheck.map((p) => p.name.trim()),
      [...rows.map((p) => p.nameKey).filter((k): k is string => !!k), ...(entryKey ? [entryKey] : [])]
    );
    if (res.data.err) throw new Error(res.data.errMsg);

    return toCheck.flatMap((row, i) => {
      const candidates = res.data.matches[i]?.candidates ?? [];
      return candidates.length ? [{ rowId: row.rowId, input: row.name.trim(), candidates }] : [];
    });
  }

  async function onSubmit(values: SharedFormValues) {
    const problem = validatePeople();
    setPeopleError(problem);
    if (problem) return;

    try {
      setLoading(true);
      const prompts = await findSimilarPrompts(people, confirmedDistinct);
      if (prompts.length > 0) {
        // Nothing is saved until the admin says whether these are the same people.
        setSimilarPrompts(prompts);
        return;
      }
      await performSave(values, people);
    } catch (err) {
      handleGlobalError(err);
    } finally {
      setLoading(false);
    }
  }

  /** Applies the answers to the "same person?" prompts, then saves. */
  async function continueAfterPrompts() {
    try {
      setLoading(true);

      const rows: PersonRow[] = [];
      for (const row of people) {
        const prompt = similarPrompts.find((p) => p.rowId === row.rowId);
        const match = prompt?.candidates.find((c) => candidateChoice(c) === prompt.choice);
        if (!match) {
          rows.push(row);
          continue;
        }

        // An older author with no key can't be referenced until it has one. Saving it generates
        // one (the modal already said so), without changing anything else about the author.
        let nameKey = match.nameKey;
        if (!nameKey) {
          const generated = await api.updateAuthor(match._id, { name: match.name });
          if (generated.data.err) throw new Error(generated.data.errMsg);
          nameKey = generated.data.author.nameKey;
        }
        rows.push({ ...row, nameKey, name: match.name, nameURL: match.nameURL ?? "" });
      }

      const distinct = [
        ...confirmedDistinct,
        ...similarPrompts.filter((p) => p.choice === "distinct").map((p) => p.rowId),
      ];

      setPeople(rows);
      setConfirmedDistinct(distinct);
      setSimilarPrompts([]);
      await performSave(getValues(), rows);
    } catch (err) {
      handleGlobalError(err);
    } finally {
      setLoading(false);
    }
  }

  async function performSave(values: SharedFormValues, rows: PersonRow[]) {
    const shared = {
      ...values,
      pictureCircle: values.pictureCircle ? "yes" : "no",
    };

    if (mode === "create") {
      const onlyNew = rows.length === 1 && !rows[0].nameKey;
      if (onlyNew) {
        // A single new author is just an author record; its key is generated by the server.
        const res = await api.createAuthor({
          ...shared,
          name: rows[0].name.trim(),
          nameURL: rows[0].nameURL,
        });
        if (res.data.err) throw new Error(res.data.errMsg);
      } else {
        const res = await api.createAuthorGroup({
          ...shared,
          members: rows.map((p) =>
            p.nameKey
              ? { nameKey: p.nameKey }
              : { new: { name: p.name.trim(), nameURL: p.nameURL } }
          ),
        });
        if (res.data.err) throw new Error(res.data.errMsg);
      }
    } else if (authorID && isGroup) {
      // New people are created first so the group can reference their keys.
      const memberKeys: string[] = [];
      for (const p of rows) {
        if (p.nameKey) {
          memberKeys.push(p.nameKey);
          continue;
        }
        const created = await api.createAuthor({
          name: p.name.trim(),
          nameURL: p.nameURL,
        });
        if (created.data.err) throw new Error(created.data.errMsg);
        memberKeys.push(created.data.author.nameKey);
      }
      const res = await api.updateAuthor(authorID, {
        ...shared,
        groupMembers: memberKeys.map((nameKey) => ({ nameKey })),
      });
      if (res.data.err) throw new Error(res.data.errMsg);
    } else if (authorID) {
      const res = await api.updateAuthor(authorID, {
        ...shared,
        name: rows[0].name.trim(),
        nameURL: rows[0].nameURL,
      });
      if (res.data.err) throw new Error(res.data.errMsg);
    }

    queryClient.invalidateQueries({ queryKey: ["authors"] });
    queryClient.invalidateQueries({ queryKey: ["author-picker-options"] });

    addNotification({
      message:
        mode === "create"
          ? "The author has been successfully added."
          : "The author's information has been successfully updated.",
      type: "success",
    });

    onClose();
  }

  async function handleImageUpload(files: FileList) {
    try {
      // FileUploader fires on every state change, including when files are cleared.
      if (uploadingImage || !authorID || !files || files.length === 0) return;

      setUploadingImage(true);
      const formData = new FormData();
      formData.append("file", files[0]);

      const res = await api.uploadAuthorImage(authorID, formData);
      if (res.data.err) throw new Error(res.data.errMsg);
      if (!res.data.url) throw new Error("Invalid response from server.");

      // Sync the form field so a subsequent save keeps the new URL and doesn't clobber other edits.
      setValue("pictureURL", res.data.url, { shouldDirty: false });
      addNotification({
        message: "The author's image has been successfully uploaded.",
        type: "success",
      });
      queryClient.invalidateQueries({ queryKey: ["authors"] });
    } catch (err) {
      handleGlobalError(err);
    } finally {
      setUploadingImage(false);
    }
  }

  async function handleDelete() {
    try {
      if (!authorID) return;
      setLoading(true);
      const res = await api.deleteAuthor(authorID);
      if (res.data.err) throw new Error(res.data.errMsg);
      queryClient.invalidateQueries({ queryKey: ["authors"] });
      onClose();
    } catch (err) {
      handleGlobalError(err);
    } finally {
      setLoading(false);
      setShowConfirmDelete(false);
    }
  }

  const creditedAs = people
    .map((p) => p.name.trim())
    .filter(Boolean)
    .join(", ");

  return (
    <Modal open={show} onClose={onClose} size="xl">
      <Modal.Header>
        <Modal.Title>{mode === "create" ? "Add" : "Edit"} Author</Modal.Title>
        <Modal.Close />
      </Modal.Header>
      <Modal.Body className="overflow-y-auto max-h-[70vh]">
        <Stack gap="xl">
          <FormSection
            title="Key"
            description="What a page or book is tagged with to credit everyone listed below. Keys are generated automatically and can't be changed."
          >
            {mode === "create" ? (
              <Text size="sm" color="muted">
                {people.length > 1 || people.some((p) => p.nameKey)
                  ? "A short key (e.g. k3x9q2m7ab) is generated for this group when you save."
                  : "A key is generated from the name when you save."}
              </Text>
            ) : entryKey ? (
              <div className="flex items-center gap-2 font-mono">
                <span>{entryKey}</span>
                <CopyButton val={entryKey}>
                  {({ copied, copy }) => (
                    <IconButton
                      icon={copied ? <IconCheck size={14} /> : <IconCopy size={14} />}
                      aria-label="Copy key"
                      variant="ghost"
                      size="sm"
                      onClick={() => {
                        copy();
                        addNotification({
                          message: "Copied to clipboard",
                          type: "success",
                          duration: 2000,
                        });
                      }}
                    />
                  )}
                </CopyButton>
              </div>
            ) : (
              <Alert
                variant="warning"
                title={isGroup ? "This group has no key" : "This author has no key"}
                message={
                  isGroup
                    ? "This group has no key yet, so a new short key will be generated when you save."
                    : `${
                        people[0]?.name || originalName || "This author"
                      } has no key yet, so a new one will be generated from the name when you save.`
                }
              />
            )}
            {mode === "edit" && !isGroup && memberOfKeys.length > 0 && (
              <Text size="sm" color="muted" className="mt-2">
                Member of: <span className="font-mono">{memberOfKeys.join(", ")}</span>
              </Text>
            )}
          </FormSection>

          <FormSection
            title={people.length > 1 || isGroup ? "Authors" : "Author"}
            description={
              canEditPeopleList
                ? `Each author only needs a name and a URL. Add more than one to credit them together (up to ${MAX_PEOPLE}).`
                : "To credit several authors together, add a new entry that lists them."
            }
          >
            <Stack gap="md">
              {people.map((person, index) => (
                <div
                  key={person.rowId}
                  className="rounded-lg border border-gray-200 p-3 flex flex-col sm:flex-row sm:items-start gap-3"
                >
                  <div className="grow grid grid-cols-1 sm:grid-cols-2 gap-3">
                    <Input
                      name={`name-${person.rowId}`}
                      label="Name"
                      placeholder="John Doe"
                      required
                      readOnly={!!person.nameKey}
                      value={person.name}
                      onChange={(e) => updatePerson(person.rowId, { name: e.target.value })}
                      helperText={
                        person.nameKey ? `Existing author (${person.nameKey}).` : undefined
                      }
                    />
                    <Input
                      name={`nameURL-${person.rowId}`}
                      label="Name URL"
                      type="url"
                      placeholder="https://example.com/johndoe"
                      readOnly={!!person.nameKey}
                      value={person.nameURL}
                      onChange={(e) => updatePerson(person.rowId, { nameURL: e.target.value })}
                    />
                  </div>
                  {canEditPeopleList && (
                    <div className="flex shrink-0 gap-1 sm:pt-6">
                      <IconButton
                        icon={<IconArrowUp size={16} />}
                        aria-label={`Move ${person.name || "author"} up`}
                        variant="ghost"
                        size="sm"
                        disabled={index === 0}
                        onClick={() => movePerson(index, -1)}
                      />
                      <IconButton
                        icon={<IconArrowDown size={16} />}
                        aria-label={`Move ${person.name || "author"} down`}
                        variant="ghost"
                        size="sm"
                        disabled={index === people.length - 1}
                        onClick={() => movePerson(index, 1)}
                      />
                      <IconButton
                        icon={<IconTrash size={16} />}
                        aria-label={`Remove ${person.name || "author"}`}
                        variant="destructive"
                        size="sm"
                        disabled={people.length === 1}
                        onClick={() =>
                          setPeople((prev) => prev.filter((p) => p.rowId !== person.rowId))
                        }
                      />
                    </div>
                  )}
                </div>
              ))}

              {canEditPeopleList && (
                <div className="flex flex-col sm:flex-row sm:items-end gap-2">
                  <Button
                    variant="outline"
                    icon={<IconPlus size={16} />}
                    disabled={people.length >= MAX_PEOPLE}
                    onClick={() => setPeople((prev) => [...prev, newPerson()])}
                  >
                    Add author
                  </Button>
                  <Combobox<Author>
                    className="grow"
                    value={null}
                    onChange={addExisting}
                    by="nameKey"
                    nullable
                    disabled={people.length >= MAX_PEOPLE}
                  >
                    <Combobox.Label>Or add an existing author</Combobox.Label>
                    <Combobox.Input<Author>
                      placeholder="Search by name or key…"
                      displayValue={() => ""}
                      onChange={(e) => setAuthorSearch(e.target.value)}
                    />
                    <Combobox.Options>
                      {selectableAuthors.map((a) => (
                        <Combobox.Option<Author> key={a.nameKey} value={a}>
                          {a.name}
                          <span className="ml-2 font-mono text-xs text-gray-500">{a.nameKey}</span>
                        </Combobox.Option>
                      ))}
                      <Combobox.Empty>
                        {searching ? "Searching…" : "No matching authors."}
                      </Combobox.Empty>
                    </Combobox.Options>
                  </Combobox>
                </div>
              )}

              {people.length > 1 && creditedAs && (
                <Text size="sm" color="muted">
                  Credited as: {creditedAs}
                </Text>
              )}
              {peopleError && <Alert variant="error" title="Check the form" message={peopleError} />}
            </Stack>
          </FormSection>

          <FormSection
            title="Affiliation"
            description="Optional institution and program credited alongside the author(s)."
          >
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              <CampusCombobox
                campusName={campusName}
                campusURL={campusURL}
                onChange={(name, url) => {
                  setValue("campusName", name, { shouldDirty: true });
                  setValue("campusURL", url, { shouldDirty: true });
                }}
              />
              <Input
                label="Campus URL"
                type="url"
                readOnly
                placeholder="Filled in when a campus is selected"
                {...register("campusURL")}
              />
              <Input
                label="Program Name"
                placeholder="OER for Good"
                {...register("programName")}
              />
              <Input
                label="Program URL"
                type="url"
                placeholder="https://oerforgood.example.com"
                {...register("programURL")}
              />
            </div>
          </FormSection>

          <FormSection
            title="Display & Attribution"
            description="Control how the picture and attribution text appear."
          >
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              <div className="sm:col-span-2 flex flex-col gap-3 sm:flex-row sm:items-start">
                <div className="flex flex-col items-center gap-1 shrink-0">
                  {pictureURL ? (
                    <img
                      src={pictureURL}
                      alt="Author picture preview"
                      className={`h-24 w-24 object-cover border border-gray-200 ${
                        pictureCircle ? "rounded-full" : "rounded-md"
                      }`}
                    />
                  ) : (
                    <div
                      className={`h-24 w-24 flex items-center justify-center bg-gray-50 border border-dashed border-gray-300 text-xs text-gray-400 text-center px-2 ${
                        pictureCircle ? "rounded-full" : "rounded-md"
                      }`}
                    >
                      No picture
                    </div>
                  )}
                </div>
                <div className="grow w-full">
                  {mode === "edit" ? (
                    <>
                      <FileUploader
                        fileTypes={ALLOWED_IMAGE_TYPES}
                        maxFiles={1}
                        maxFileSize={MAX_IMAGE_SIZE}
                        disabled={uploadingImage}
                        onUpload={handleImageUpload}
                      />
                      <p className="mt-1 text-xs text-gray-500">
                        {uploadingImage
                          ? "Uploading picture…"
                          : "Upload a JPEG, PNG, or WebP image (max 5 MB). The picture is saved immediately."}
                      </p>
                    </>
                  ) : (
                    <p className="text-sm text-gray-500">
                      Save the author first to upload a picture.
                    </p>
                  )}
                </div>
              </div>
              <Input
                label="Picture URL"
                type="url"
                placeholder="https://example.com/photo.jpg"
                className="sm:col-span-2"
                helperText="Automatically set when you upload a picture. You can also paste an external URL."
                {...register("pictureURL")}
              />
              <Input
                label="Attribution Prefix"
                placeholder="e.g. Access for free at"
                className="sm:col-span-2"
                {...register("attributionPrefix")}
              />
              <div className="sm:col-span-2">
                <Controller
                  control={control}
                  name="pictureCircle"
                  render={({ field }) => (
                    <Checkbox
                      name="pictureCircle"
                      label="Display picture as circle"
                      description="When enabled, the picture is cropped to a circular frame."
                      checked={field.value}
                      onChange={(checked) => field.onChange(checked)}
                    />
                  )}
                />
              </div>
            </div>
          </FormSection>

          <FormSection
            title="Note"
            description="Optional call-to-action shown with the attribution."
          >
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              <Input
                label="Note"
                placeholder="e.g. Donate to the author's research program."
                className="sm:col-span-2"
                {...register("note")}
              />
              <Input
                label="Note URL"
                type="url"
                placeholder="https://example.com/note"
                className="sm:col-span-2"
                {...register("noteURL")}
              />
            </div>
          </FormSection>

          {showConfirmDelete && (
            <Stack gap="sm">
              <Alert
                variant="error"
                title={isGroup ? "Delete this author group?" : "Delete this author?"}
                message={
                  isGroup
                    ? "The authors in it are not deleted, but pages tagged with this key will no longer resolve to it."
                    : "This action cannot be undone."
                }
              />
              <div className="flex gap-2">
                <Button
                  variant="destructive"
                  icon={<IconTrash size={16} />}
                  loading={loading}
                  onClick={handleDelete}
                >
                  Confirm Delete
                </Button>
                <Button variant="secondary" onClick={() => setShowConfirmDelete(false)}>
                  Cancel
                </Button>
              </div>
            </Stack>
          )}
        </Stack>
      </Modal.Body>
      <Modal.Footer>
        <div className="flex justify-between items-center w-full">
          <div>
            {mode === "edit" && authorID && !showConfirmDelete && (
              <Button
                variant="destructive"
                icon={<IconTrash size={16} />}
                onClick={() => setShowConfirmDelete(true)}
              >
                Delete
              </Button>
            )}
          </div>
          <div className="flex gap-2">
            <Button variant="outline" onClick={onClose} disabled={loading}>
              Cancel
            </Button>
            <Button
              variant="primary"
              icon={<IconDeviceFloppy size={16} />}
              onClick={handleSubmit(onSubmit)}
              loading={loading}
              disabled={similarPrompts.length > 0}
            >
              {mode === "create" ? "Add Author" : "Save Changes"}
            </Button>
          </div>
        </div>
      </Modal.Footer>
      <SimilarAuthorsModal
        open={similarPrompts.length > 0}
        prompts={similarPrompts}
        renameOnly={mode === "edit" && !isGroup}
        loading={loading}
        onChoose={(rowId, choice) =>
          setSimilarPrompts((prev) =>
            prev.map((p) => (p.rowId === rowId ? { ...p, choice } : p))
          )
        }
        onConfirm={continueAfterPrompts}
        onCancel={() => setSimilarPrompts([])}
      />
    </Modal>
  );
};

export default ManageAuthorModal;
