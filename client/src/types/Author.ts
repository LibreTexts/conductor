
export type Author = {
    _id?: string;
    orgID: string;
    nameKey: string; // Unique identifier for the author within an org
    name: string;
    nameURL?: string;
    note?: string;
    noteURL?: string;
    campusName?: string;
    campusURL?: string;
    pictureCircle?: string; // i.e. "yes" or "no"
    pictureURL?: string;
    programName?: string;
    programURL?: string;
    attributionPrefix?: string;
    userUUID?: string;
    groupMembers?: AuthorGroupMember[]; // Set only on a group: the individual authors it stands for
    autoName?: boolean; // Groups only. When not false, the name is derived from the members
    memberOfKeys?: string[]; // Authors only: the keys of the groups this author belongs to
}

// A group's membership of one author. The optional fields override that author's own
// affiliation for this group only.
export type AuthorGroupMember = {
    nameKey: string;
    campusName?: string;
    campusURL?: string;
    programName?: string;
    programURL?: string;
}

export type CreateAuthorGroupPayload = {
    // Keys are always generated by the server and are never sent.
    name?: string; // Custom display name; derived from the members when omitted
    members: Array<
        Partial<Omit<AuthorGroupMember, "nameKey">> & {
            nameKey?: string; // An existing author...
            new?: Partial<Omit<Author, "_id" | "orgID" | "nameKey">> & { name: string }; // ...or one to create
        }
    >;
}


// An existing author whose name resembles a typed name.
export type SimilarAuthorCandidate = {
    _id: string;
    nameKey?: string; // Missing on older records; one is generated if this author is chosen

    name: string;
    nameURL?: string;
    campusName?: string;
    score: number;
}

export type SimilarAuthorMatch = {
    input: string;
    candidates: SimilarAuthorCandidate[];
}
